import tailwindcss from '@tailwindcss/vite'
import react from '@vitejs/plugin-react'
import { readFileSync } from 'node:fs'
import { configDefaults, defineConfig } from 'vitest/config'
import { VitePWA } from 'vite-plugin-pwa'

const DARK = '#0e0d0c'

/** Version from package.json, shown on the "Sobre" screen. */
const { version } = JSON.parse(
  readFileSync(new URL('./package.json', import.meta.url), 'utf8'),
) as { version: string }

// https://vite.dev/config/
export default defineConfig({
  // `define` replaces the text __APP_VERSION__ in the code with the value, at build time.
  define: {
    __APP_VERSION__: JSON.stringify(version),
  },
  plugins: [
    react(),
    tailwindcss(),
    VitePWA({
      // 'prompt': a new version only comes in when the user taps "Atualizar".
      // Avoids reloading the app on its own in the middle of a set.
      registerType: 'prompt',
      // The icons already enter the precache via globPatterns below; without this, they would enter twice.
      includeManifestIcons: false,
      manifest: {
        name: 'Encore',
        short_name: 'Encore',
        description: 'Offline-first strength workout log.',
        lang: 'pt-BR',
        start_url: '/treino',
        scope: '/',
        display: 'standalone',
        orientation: 'portrait',
        theme_color: DARK,
        background_color: DARK,
        // Generated by `pnpm generate-icons` (see pwa-assets.config.ts).
        icons: [
          { src: 'pwa-64x64.png', sizes: '64x64', type: 'image/png' },
          { src: 'pwa-192x192.png', sizes: '192x192', type: 'image/png' },
          { src: 'pwa-512x512.png', sizes: '512x512', type: 'image/png' },
          {
            src: 'maskable-icon-512x512.png',
            sizes: '512x512',
            type: 'image/png',
            purpose: 'maskable',
          },
        ],
      },
      workbox: {
        // Precache of the WHOLE app (code, styles, fonts and icons).
        globPatterns: ['**/*.{js,css,html,svg,png,ico,woff2}'],
        // Any navigation (e.g. opening /historico offline) falls back to index.html,
        // and React Router decides which screen to show.
        navigateFallback: 'index.html',
        cleanupOutdatedCaches: true,
      },
    }),
  ],
  test: {
    // Simulates the browser (DOM) in Node to test components.
    environment: 'jsdom',
    setupFiles: ['src/test/setup.ts'],
    // End-to-end specs (Playwright) run with `pnpm e2e`, not with Vitest.
    exclude: [...configDefaults.exclude, 'e2e/**'],
  },
})
